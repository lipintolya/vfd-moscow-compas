/**
 * Неразрывные пробелы по правилам русской вёрстки — для текстов из данных
 * (в разметке .astro их ставят вручную через &nbsp;):
 *   - короткое слово (предлог, союз, частица: «в», «и», «по», «не»)
 *     не остаётся в конце строки — привязывается к следующему;
 *   - тире не начинает строку — привязывается к предыдущему слову;
 *   - число не отрывается от слова после него («15 лет»).
 * Переводы строк (\n) не трогает.
 */
const NBSP = ' '

export function typograph(text: string): string {
  return text
    // дважды — для цепочек коротких слов: «и в доме»
    .replace(/(^|[\s(«])([а-яё]{1,2}) /gi, `$1$2${NBSP}`)
    .replace(/(^|[\s(«])([а-яё]{1,2}) /gi, `$1$2${NBSP}`)
    .replace(/ — /g, `${NBSP}— `)
    .replace(/(\d) (?=[а-яё])/gi, `$1${NBSP}`)
}
