/**
 * src/data/task-categories.ts
 *
 * SEO-лендинги /catalog/<slug>/ «под задачу покупателя» — высокие двери,
 * двери в ванную, недорогие двери. От покрытий, цветов и стилей
 * (door-/color-/style-categories.ts) отличаются тем, что отбирает моделей не
 * поле каталога, а задача: либо серии из статьи салона, либо ценовая
 * корзина, либо никакая — тогда страница ведёт в каталог и сама отвечает на
 * вопрос (высокие двери: высоту выбирают при заказе, а не в карточке).
 *
 * Факты — из статей салона («Высокие межкомнатные двери…», «Какую дверь
 * выбрать в ванную комнату…») и из данных сайта: высоты — door-sizes.ts и
 * скрытые двери; цены и сроки подставляются из ARTICLE_VARS (article-vars.ts),
 * цифры каталога — из карточек при сборке (CatalogStats). Не придумывать:
 * сроки и надбавки обычных высоких дверей салон не называл — «зависит от
 * серии, назовут при расчёте».
 *
 * КАК ДОБАВИТЬ: объект в TASK_CATEGORIES — страница появится сама
 * (src/pages/catalog/[slug].astro), попадёт в «Подборки» каталога, на
 * главную (Directions), в подвал, /llms.txt и sitemap. Статья по теме —
 * articleSlug (id статьи в Strapi), пропавшая статья роняет сборку.
 */
