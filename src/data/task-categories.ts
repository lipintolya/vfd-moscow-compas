/** Что известно о подборке после отбора моделей — считается при сборке */
export interface CatalogStats {
  count: number
  minPrice: number
  /** Покрытия подборки: название и slug, как в каталоге */
  coatings: { name: string; slug: string }[]
  /** Названия серий подборки */
  series: string[]
}

export type TaskSelect = { series: string[] } | { maxPrice: number }

export interface TaskSection {
  title: string
  paragraphs?: string[]
  bullets?: string[]
  links?: { href: string; label: string }[]
}

export interface TaskCategory {
  slug: string
  h1: string
  metaTitle: string
  /** Одна строка о странице — для /llms.txt */
  summary: string
  /** Какие модели показать; нет — страница без сетки, кнопка ведёт в каталог */
  select?: TaskSelect
  /** Работы портфолио (id в Strapi); пропавшая — ошибка сборки */
  works?: string[]
  /** Статья по теме (id) — карточка «Статья по теме» */
  articleSlug?: string
  /** Тексты, где нужны цифры подборки */
  text: (s: CatalogStats) => {
    intro: string
    metaDescription: string
    sections: TaskSection[]
    faq: DoorCategoryFaq[]
  }
}

