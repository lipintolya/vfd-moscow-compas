/**
 * Направления плинтуса на /catalog/plintus/ помимо напольного из МДФ
 * (src/data/plintus.ts): с LED-подсветкой, скрытый, микроплинтус,
 * шпонированный. Ассортимент, фото и характеристики — от поставщика
 * (согласовано), название производителя и названия моделей на сайт не
 * выводятся. Цена — по запросу у менеджера, как у напольного плинтуса.
 *
 * Фото — assets/plintus-lines/ → npm run gen:plintus-lines →
 * public/renders/plintus/ + plintus-lines-images.json. Фото с подсветкой
 * названы номером профиля напольного каталога (led-07 — профиль № 7):
 * у поставщика это те же модели с пазом под ленту.
 */
import images from './plintus-lines-images.json'
import { PLINTUS } from './plintus'

export interface LineImage { src: string; srcset: string; large: string; width: number; height: number; alt: string }

const table = images as Record<string, { widths: number[]; width: number; height: number }>
const img = (name: string, alt: string): LineImage => {
  const m = table[name]
  if (!m) throw new Error(`Плинтус: нет фото «${name}» — assets/plintus-lines/${name}.webp, затем npm run gen:plintus-lines`)
  const file = (w: number) => `/renders/plintus/${name}-${w}.webp`
  return { src: file(m.widths[0]!), srcset: m.widths.map((w) => `${file(w)} ${w}w`).join(', '), large: file(m.widths.at(-1)!), width: m.width, height: m.height, alt }
}

