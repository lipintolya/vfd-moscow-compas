/**
 * src/data/style-categories.ts
 *
 * SEO-лендинги под /catalog/<slug> по стилю интерьера. В отличие от
 * door-categories.ts (покрытие) и color-categories.ts (цвет — оба реальные
 * поля в БД), стиль — не поле каталога, а редакторская характеристика,
 * которую копирайтер уже вписал в описания конкретных серий
 * (src/data/series-descriptions.ts, tagline/description/features). Список
 * серий здесь — это те серии, чей СОБСТВЕННЫЙ текст явно называет стиль
 * (грепом по словам «лофт»/«минимализм» в их описаниях), а не придуманная
 * категоризация. Серия может стоять в обеих категориях, если её описание
 * упоминает оба стиля — так и есть у большинства (лофт и минимализм в
 * современных интерьерах обычно совместимы, это не взаимоисключающие теги).
 *
 * КАК ДОБАВИТЬ/ИЗМЕНИТЬ: правь seriesSlugs здесь. Если добавляешь новую
 * серию в series-descriptions.ts с явным упоминанием стиля в тексте —
 * добавь её slug и сюда, чтобы лендинг не расходился с редакционным текстом.
 *
 * Исключение — colorFilter: некоторые стили (скандинавский) на деле не про
 * конкретные серии, а про пересечение цвет+покрытие («любая белая дверь в
 * Эмалекс/Эмаль»), фиксированный список серий тут только устареет при
 * добавлении новых белых моделей. Если задан colorFilter, StyleCategoryLanding
 * отбирает карточки по нему вместо seriesSlugs (seriesSlugs в этом случае
 * оставляй пустым массивом — не используется).
 */

import type { DoorCategoryFaq } from './door-categories'

export interface StyleCategory {
  slug: string
  eyebrow: string
  h1: string
  intro: string
  metaTitle: string
  metaDescription: string
  /** Slug'и серий (ключи seriesDescriptions / seriesSlug карточек). Пустой
      массив, если задан colorFilter (см. комментарий выше). */
  seriesSlugs: string[]
  /** Альтернатива seriesSlugs — фильтр по цвету+покрытию вместо жёсткого
      списка серий, см. комментарий выше. */
  colorFilter?: {
    /** Регистронезависимые подстроки для матча по названию цвета модели —
        тот же принцип, что и ColorCategory.colorKeywords. */
    colorKeywords: string[]
    coatingSlugs: string[]
  }
  faq: DoorCategoryFaq[]
}

