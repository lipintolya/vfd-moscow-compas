/** Модель, которой принадлежит кадр; нет такой в каталоге — ошибка сборки, а не тихая дыра */
export function sceneDoor(s: DoorScene): EntranceDoor {
  const d = doorById(s.door)
  if (!d) throw new Error(`Рендеры «на доме»: кадр «${s.slot}» — в каталоге входных дверей нет модели «${s.door}»`)
  return d
}

/** Описание картинки для поиска по картинкам: что за модель, что видно, что это визуализация, чьё */
export const sceneAlt = (s: DoorScene) => `${sceneDoor(s).title}, визуализация: ${s.what} — ${SITE.studioName}`

