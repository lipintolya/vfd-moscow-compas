/**
 * Рендеры «дверь на доме» — визуализации моделей входных дверей из каталога
 * на фасадах частных домов. Один кадр = одна модель каталога (id из
 * entrance-doors-catalog.json); у модели бывает несколько кадров (Термолаб 2 Про:
 * горизонтальный и вертикальный).
 *
 * Где показываются (выводит src/lib/entrance-scenes.ts, ничего не набирается руками):
 *  - обложка (`cover`) — фон первого экрана /catalog/vhodnye-dveri/ и og:image;
 *  - по первому кадру каждой модели — лента «Как дверь смотрится на фасаде дома»
 *    на той же странице (обложка в ленту не попадает — не повторяем кадр);
 *  - все кадры модели — блок под фото на странице самой модели;
 *  - `home` — фото плитки «Входные двери» на главной (вертикальный кадр).
 *
 * Файлы: assets/entrance-renders/<slot>.webp → npm run gen:entrance-renders
 * (тот же конвейер, что у рендеров путеводителя). Имя файла — slot.
 * Правила кадров — как у всех рендеров: без вывесок, текстов и названий производителей.
 */
import { SITE } from '../config/site'
import { doorById } from './entrance-doors'
import type { EntranceDoor } from './entrance-doors'

export interface DoorScene {
  /** Имя файла в assets/entrance-renders/ без расширения */
  slot: string
  /** id модели в каталоге входных дверей */
  door: string
  /** Что на кадре — для описания картинки (alt); название модели и студию добавляет sceneAlt */
  what: string
  /** Обложка первого экрана каталога; в ленте на странице каталога не повторяется */
  cover?: true
  /** Точка на двери (доли ширины и высоты рендера) — у обложки: по наведению открывается карточка модели */
  spot?: { x: number; y: number }
  /** Фото плитки «Входные двери» на главной (вертикальный кадр) — одно на весь сайт */
  home?: true
}

