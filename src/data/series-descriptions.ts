export interface SeriesSpec {
  tagline:     string
  description: string
  features:    string[]
  coating:     string
  material:    string
  edge:        string
  thickness:   string
  /** Обложка hero страницы серии. Пусто → на странице серии используется
      фото первой (по цене) модели серии как фолбэк. */
  heroImage?:  string
  /** Превью для карточки серии в сетке /catalog (SeriesCard) — если не
      указано, используется heroImage, затем фото первой модели. Указывай
      отдельно, когда для карточки и полноразмерного hero-баннера нужны
      разные кадры (разный кроп/ракурс рендера). */
  previewImage?: string
  /** Промо-постеры коллекции — реальные фото/рендеры (не инфографика с
      текстом, для этого infoImage), показываются фото-галереей под
      описанием в «О коллекции». */
  posterImages?: string[]
  /** Инфографика/презентация серии — картинка с текстом внутри (не фото),
      показывается под описанием в «О коллекции». object-fit:contain
      (variant="wide" в InfoImageViewer) — обрезать нельзя, там текст. */
  infoImage?:  string
  /** Реальное соотношение сторон infoImage (напр. "3508 / 2003") — у каждой
      картинки своё, без этого либо обрезка, либо пустые поля по бокам.
      Не указано → фолбэк 16:9 (см. [slug].astro). */
  infoImageAspect?: string
  /** Подпись под infoImage. Не указано → «Презентация серии {имя}» — подходит
      для персональной презентации серии, но не для общей картинки (напр.
      единая палитра цветов эмали emal_covers.webp на несколько серий сразу). */
  infoImageCaption?: string
  /** Техническая инфографика конструкции полотна (разрез/материалы) —
      показывается рядом со списком в блоке «Характеристики», а не в
      «О коллекции» (там infoImage). Не указано → блок «Характеристики»
      остаётся текстовым списком на всю ширину, как раньше. */
  specsImage?: string
}

