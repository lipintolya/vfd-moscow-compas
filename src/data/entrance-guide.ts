const visualOf = (slot: string) => {
  const v = GUIDE_VISUALS.find((x) => x.slot === slot)
  if (!v) throw new Error(`Путеводитель: нет места «${slot}» — src/data/entrance-guide.ts`)
  return v
}

/* ---------- Цифры каталога ---------- */

const spec = (d: EntranceDoor, label: string) => d.specs.find((s) => s.label === label)?.value
const numbers = (label: string, re: RegExp) =>
  ENTRANCE_DOORS.map((d) => Number(spec(d, label)?.match(re)?.[1])).filter((n) => Number.isFinite(n) && n > 0)
const range = (xs: number[], sep = '–') => (Math.min(...xs) === Math.max(...xs) ? `${xs[0]}` : `${Math.min(...xs)}${sep}${Math.max(...xs)}`)
const count = (pred: (d: EntranceDoor) => boolean) => ENTRANCE_DOORS.filter(pred).length
const models = (n: number) => `${n} ${pluralRu(n, ['модель', 'модели', 'моделей'])}`

const thickness = numbers('Толщина, вес', /Толщина двери (\d+)/)
const steels = ENTRANCE_DOORS.map((d) => Number(d.steel.replace(',', '.'))).filter(Boolean)
const steelRange = `${Math.min(...steels)}–${Math.max(...steels)}`.replace(/\./g, ',')
const total = ENTRANCE_DOORS.length
const withThermo = count((d) => !!spec(d, 'Терморазрыв'))
const lock4 = count((d) => /4-го/.test(spec(d, 'Основной замок') ?? ''))
const cylinder = count((d) => /^Цилиндровый/i.test(spec(d, 'Основной замок') ?? ''))
const sulvald = count((d) => /^Сувальдный/i.test(spec(d, 'Основной замок') ?? ''))
const magnetic = count((d) => /магнит/i.test(spec(d, 'Контуры уплотнения') ?? ''))
const acoustic = count((d) => !!spec(d, 'Ультрашум®'))
const threshold = count((d) => !!spec(d, 'Защита порога'))
const polyamide = [...new Set(ENTRANCE_DOORS.map((d) => spec(d, 'Терморазрыв')?.match(/(\d+) мм/)?.[1]).filter(Boolean))]
/* Размер по коробу: «960х2050 мм (внешний 1130х2130 мм)» — на сколько короб шире полотна */
const box = ENTRANCE_DOORS.map((d) => spec(d, 'Размер по коробу')?.match(/^(\d+)х\d+ мм \(внешний (\d+)х/)).find(Boolean)
const boxExtra = box ? Number(box[2]) - Number(box[1]) : 0

