/** Какую группу каталога советуем и почему — одной фразой */
export function pickResult(place: PickPlace, need: PickNeed): { group: DoorGroupId; why: string } {
  if (need === 'smart') {
    return { group: 'smart', why: place === 'house' ? 'С электронным замком — подойдёт и в дом: смотрите ещё на терморазрыв в характеристиках.' : 'Электронный замок открывается отпечатком, пин-кодом, брелком или со смартфона.' }
  }
  if (place === 'house') {
    return need === 'light'
      ? { group: 'glass', why: 'Уличные двери со стеклопакетом: трёхкамерный стеклопакет, нержавеющий порог в комплекте.' }
      : { group: 'thermo', why: 'Терморазрыв не даёт двери промерзать, на ней нет наледи и конденсата.' }
  }
  return { group: 'flat', why: need === 'light' ? 'В квартире стеклопакет не нужен — выберите дверь с зеркалом внутри: в прихожей станет светлее.' : 'Утеплённое полотно и три контура уплотнения: тихо, без сквозняков и надёжно.' }
}

